import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { once } from 'node:events';
import test from 'node:test';
import express from 'express';
import { aiGatewayApi } from './index.mjs';

test('a API responde à verificação local e identifica rota ou método inválido', async (t) => {
  const app = express();
  app.use(aiGatewayApi);
  const server = createServer(app).listen(0, '127.0.0.1');
  t.after(() => new Promise((resolve) => server.close(resolve)));
  await once(server, 'listening');
  const base = 'http://127.0.0.1:' + server.address().port;
  assert.equal((await fetch(base + '/api/session')).status, 401);
  const quote = base + '/api/budget/quote';
  assert.equal((await fetch(quote, { method: 'POST' })).status, 401);
  const wrongMethod = await fetch(quote);
  assert.equal(wrongMethod.status, 405);
  assert.equal(wrongMethod.headers.get('Allow'), 'POST');
  assert.equal((await fetch(base + '/api/executions', { method: 'POST' })).status, 401);
  assert.equal((await fetch(base + '/api/executions/sample')).status, 401);
  assert.equal((await fetch(base + '/api/executions/sample/media/0')).status, 401);
  assert.equal((await fetch(base + '/api/executions/sample', { method: 'POST' })).status, 405);
  const health = await fetch(base + '/api/health');
  assert.equal(health.status, 200);
  assert.deepEqual(await health.json(), { status: 'ok' });
  assert.equal((await fetch(base + '/api/missing')).status, 404);
  assert.equal((await fetch(base + '/api/health', { method: 'POST' })).status, 405);
});
